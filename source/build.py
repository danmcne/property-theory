"""Generate all TPTP files from theory.py.

Outputs (relative to the repository root):
  libertarian-property-theory-v0.23.thf   full theory, THF (record file)
  libertarian-property-theory-v0.23.p     full theory, TFF
  minimal/thf/<theorem>.thf               one Leo-III problem per theorem
  minimal/tff/<theorem>.p                 one Vampire problem per theorem
  minimal/MANIFEST.md                     dependency table (axioms + lemmas)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import tptp  # noqa: E402
import theory  # noqa: E402

VERSION = '0.23'
STEM = 'libertarian-property-theory-v%s' % VERSION


def load():
    """Parse and type-check everything; return name->entry dicts."""
    axioms = {}
    for a in theory.A + theory.CONTRAST:
        a['ast'] = tptp.parse(a['text'])
        tptp.typecheck(a['ast'], theory.SIG, {}, where=a['name'])
        if a['name'] in axioms:
            raise ValueError("duplicate axiom " + a['name'])
        axioms[a['name']] = a
    thms, seen = {}, []
    for t in theory.TH:
        t['ast'] = tptp.parse(t['text'])
        tptp.typecheck(t['ast'], theory.SIG, {}, where=t['name'])
        for d in t['deps'] + t['contrast']:
            if d not in axioms:
                raise ValueError("%s: unknown dependency %s" % (t['name'], d))
        for l in t['lemmas']:
            if l not in seen:
                raise ValueError("%s: lemma %s is not an EARLIER theorem (DAG check)" % (t['name'], l))
        seen.append(t['name'])
        thms[t['name']] = t
    return axioms, thms


def closure(name, thms):
    """Axioms a theorem rests on, following lemmas transitively."""
    t = thms[name]
    acc = set(t['deps']) | set(t['contrast'])
    for l in t['lemmas']:
        acc |= closure(l, thms)
    return acc


def problem_for(t, axioms, thms, lang):
    items = []
    for d in t['contrast']:
        items.append((d, axioms[d]['ast'], 'CONTRAST axiom (control view): ' + axioms[d]['gloss']))
    for d in t['deps']:
        items.append((d, axioms[d]['ast'], axioms[d]['gloss']))
    for l in t['lemmas']:
        items.append((l, thms[l]['ast'], 'LEMMA (proved in its own problem): ' + thms[l]['gloss']))
    head = ("Libertarian Property Theory v%s -- minimal problem for: %s\n"
            "%s\n"
            "Generated by source/build.py from source/theory.py. Do not edit."
            % (VERSION, t['name'], t['gloss']))
    return tptp.problem(lang, theory.SORTS, theory.SIG, {}, items, (t['name'], t['ast']), head)


def full_theory(axioms, lang):
    items = [(a['name'], a['ast'], '[%s/%s] %s' % (a['group'], a['kind'], a['gloss']))
             for a in theory.A]
    head = ("Libertarian Property Theory v%s -- the full axiom set (%s).\n"
            "Generated by source/build.py from source/theory.py. Do not edit.\n"
            "Ownership is the right to exclude: owns(P,O,Q,T) = P may exclude Q from O at T.\n"
            "Theorems: see minimal/ and minimal/MANIFEST.md."
            % (VERSION, 'THF, for Leo-III' if lang == 'thf' else 'TFF, for Vampire'))
    return tptp.problem(lang, theory.SORTS, theory.SIG, {}, items, None, head)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def main():
    axioms, thms = load()
    write(os.path.join(ROOT, STEM + '.thf'), full_theory(axioms, 'thf'))
    write(os.path.join(ROOT, STEM + '.p'), full_theory(axioms, 'tff'))
    for d in ('thf', 'tff'):
        dd = os.path.join(ROOT, 'minimal', d)
        if os.path.isdir(dd):
            for f in os.listdir(dd):
                os.remove(os.path.join(dd, f))
    for t in thms.values():
        write(os.path.join(ROOT, 'minimal', 'thf', t['name'] + '.thf'), problem_for(t, axioms, thms, 'thf'))
        write(os.path.join(ROOT, 'minimal', 'tff', t['name'] + '.p'), problem_for(t, axioms, thms, 'tff'))
    # an axiom marked 'derived' must follow from the axioms it names
    for a in theory.A:
        if a.get('derived'):
            pseudo = dict(name='derived_' + a['name'], ast=a['ast'], deps=a['derived'], lemmas=[], contrast=[],
                          gloss='Redundancy check: ' + a['gloss'])
            write(os.path.join(ROOT, 'minimal', 'thf', pseudo['name'] + '.thf'), problem_for(pseudo, axioms, thms, 'thf'))
            write(os.path.join(ROOT, 'minimal', 'tff', pseudo['name'] + '.p'), problem_for(pseudo, axioms, thms, 'tff'))
    n_ax = sum(1 for a in theory.A if a['kind'] == 'axiom')
    n_def = sum(1 for a in theory.A if a['kind'] == 'definition')
    print("parsed and type-checked: %d axioms, %d definitions, %d contrast axioms, %d theorems"
          % (n_ax, n_def, len(theory.CONTRAST), len(thms)))
    return axioms, thms


if __name__ == '__main__':
    main()
