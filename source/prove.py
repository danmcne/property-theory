"""Run Leo-III (THF) and Vampire (TFF) on every minimal problem.

Usage: python3 source/prove.py [--leo PATH_TO_leo3.jar] [--vampire PATH] [-t SECONDS] [names...]
Writes results/proofs.json and minimal/MANIFEST.md.
A theorem counts as verified only if BOTH provers report SZS status Theorem.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import build  # noqa: E402
import theory  # noqa: E402

DEFAULT_LEO = os.environ.get('LEO3_JAR', os.path.join(ROOT, '..', 'tools', 'leo3.jar'))
DEFAULT_VAMPIRE = os.environ.get('VAMPIRE', os.path.join(ROOT, '..', 'tools', 'vampire'))
DEFAULT_E = os.environ.get('EPROVER', os.path.join(ROOT, '..', 'tools', 'eprover', 'PROVER', 'eprover'))


def run_vampire(exe, path, t):
    try:
        out = subprocess.run([exe, '--mode', 'casc', '-t', str(t), path],
                             capture_output=True, text=True, timeout=t + 30).stdout
    except subprocess.TimeoutExpired:
        return 'Timeout', []
    m = re.search(r"SZS status (\w+)", out)
    used = sorted(set(re.findall(r"file\('[^']*','([^']*)'\)", out)))
    return (m.group(1) if m else 'Unknown'), used


def run_leo(jar, path, t, eprover=None):
    cmd = ['java', '-jar', jar, path, '-t', str(t)]
    if eprover:
        cmd += ['--atp', 'e=' + eprover]
    try:
        out = subprocess.run(cmd,
                             capture_output=True, text=True, timeout=t + 60).stdout
    except subprocess.TimeoutExpired:
        return 'Timeout', []
    m = re.search(r"SZS status (\w+)", out)
    u = re.search(r"Axioms used in derivation \(\d+\):\s*(.*)", out)
    used = sorted(x.strip() for x in u.group(1).split(',')) if u and u.group(1).strip() else []
    return (m.group(1) if m else 'Unknown'), used


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--leo', default=DEFAULT_LEO)
    ap.add_argument('--vampire', default=DEFAULT_VAMPIRE)
    ap.add_argument('--eprover', default=DEFAULT_E,
                    help="E binary used by Leo-III as its first-order back end ('' = Leo-III alone)")
    ap.add_argument('-t', type=int, default=120)
    ap.add_argument('--record', default='proofs.json',
                    help="results file name; the manifest is written only for proofs.json")
    ap.add_argument('names', nargs='*')
    a = ap.parse_args()
    axioms, thms = build.main()
    names = a.names or (list(thms) + ['derived_' + x['name'] for x in theory.A if x.get('derived')])
    eprover = a.eprover if a.eprover and os.path.exists(a.eprover) else None
    print("Leo-III back end: %s" % ('E (' + eprover + ')' if eprover else 'none (Leo-III alone)'))

    def job(n):
        v = run_vampire(a.vampire, os.path.join(ROOT, 'minimal', 'tff', n + '.p'), a.t)
        l = run_leo(a.leo, os.path.join(ROOT, 'minimal', 'thf', n + '.thf'), a.t, eprover)
        return n, v, l

    res = {}
    with ThreadPoolExecutor(max_workers=2) as ex:
        for n, v, l in ex.map(job, names):
            res[n] = dict(vampire=v[0], vampire_used=[x for x in v[1] if x != n],
                          leo3=l[0], leo3_used=l[1], leo3_backend='E' if eprover else 'none')
            ok = v[0] == 'Theorem' and l[0] == 'Theorem'
            print("%-36s vampire=%-9s leo3=%-9s %s" % (n, v[0], l[0], 'OK' if ok else '<<< CHECK'))
    os.makedirs(os.path.join(ROOT, 'results'), exist_ok=True)
    path = os.path.join(ROOT, 'results', a.record)
    old = json.load(open(path)) if os.path.exists(path) and a.names else {}
    old.update(res)
    json.dump(old, open(path, 'w'), indent=1, sort_keys=True)
    if a.record == 'proofs.json':
        write_manifest(thms, old)
    bad = [n for n in names if not (res[n]['vampire'] == 'Theorem' and res[n]['leo3'] == 'Theorem')]
    print("\n%d/%d theorems proved by both provers" % (len(names) - len(bad), len(names)))
    return 1 if bad else 0


def write_manifest(thms, res):
    L = ["# Theorem manifest — v%s" % build.VERSION, "",
         "Generated by `source/prove.py`. Each theorem has one minimal problem in `minimal/thf/` (Leo-III)",
         "and `minimal/tff/` (Vampire) that contains ONLY the axioms and lemmas listed here.",
         "Lemmas are earlier theorems; the lemma graph is checked to be acyclic when the files are built.",
         "\"Rests on\" is the transitive closure: every axiom or definition the theorem depends on.",
         "\"Used\" lists the premises each prover's proof actually cited.", ""]
    for t in theory.TH:
        n = t['name']
        r = res.get(n, {})
        L.append("## `%s` — %s" % (n, t['tag']))
        L.append("")
        L.append(t['gloss'])
        L.append("")
        L.append("- Premises given: %s" % ", ".join("`%s`" % x for x in t['contrast'] + t['deps'] + t['lemmas']) or "- Premises given: none")
        L.append("- Rests on: %s" % ", ".join("`%s`" % x for x in sorted(build.closure(n, thms))))
        L.append("- Vampire: %s; used %s" % (r.get('vampire', '—'), ", ".join(r.get('vampire_used', [])) or '—'))
        L.append("- Leo-III (back end: %s): %s; used %s" % (r.get('leo3_backend', '—'), r.get('leo3', '—'),
                                                           ", ".join(r.get('leo3_used', [])) or '—'))
        L.append("")
    with open(os.path.join(ROOT, 'minimal', 'MANIFEST.md'), 'w') as fh:
        fh.write("\n".join(L))


if __name__ == '__main__':
    sys.exit(main())
